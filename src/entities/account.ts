export function getCountryFlag(country: string) {
  const trimmedCountry = country.trim();

  if (!trimmedCountry) {
    return '';
  }

  const code = COUNTRY_CODE_BY_NAME[trimmedCountry as CountryOption];

  if (!code) {
    return '🌍';
  }

  return code
    .toUpperCase()
    .split('')
    .map((char) => String.fromCodePoint(127397 + char.charCodeAt(0)))
    .join('');
}

