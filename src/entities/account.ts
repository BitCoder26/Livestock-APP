export function getCurrencyCodeForCountry(country: string) {
  switch (country.trim().toLowerCase()) {
    case 'united kingdom':
    case 'ireland':
      return 'GBP';
    case 'united states':
      return 'USD';
    case 'canada':
      return 'CAD';
    case 'australia':
      return 'AUD';
    case 'new zealand':
      return 'NZD';
    case 'south africa':
      return 'ZAR';
    default:
      return 'GBP';
  }
}

export function formatCurrencyPrefix(country: string) {
  const code = getCurrencyCodeForCountry(country);

  switch (code) {
    case 'GBP':
      return '£';
    case 'USD':
    case 'CAD':
    case 'AUD':
    case 'NZD':
      return '$';
    case 'ZAR':
      return 'R';
    default:
      return '£';
  }
}
